// Generates app/theme-light.css from app/globals.css.
// Every rule that sets a colour is repeated under :root[data-theme="light"] with the colour's
// lightness flipped (hue and saturation kept), so dark navy becomes light grey-blue, light text
// becomes dark text, and status colours keep their meaning. Hand-tuned exceptions live in
// app/theme-light-overrides.css, which is loaded after this file.
// Run: npm run theme:light   (re-run after changing colours in globals.css)
import fs from "node:fs";

const SOURCE = new URL("../app/globals.css", import.meta.url);
const TARGET = new URL("../app/theme-light.css", import.meta.url);
const SCOPE = ':root[data-theme="light"]';
const NAMED = { white: "#ffffff", black: "#000000" };

function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h / 6, s, l];
}
function hslToRgb(h, s, l) {
  if (s === 0) return [l, l, l].map(v => Math.round(v * 255));
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s, p = 2 * l - q;
  const f = t => { t = (t + 1) % 1; return t < 1 / 6 ? p + (q - p) * 6 * t : t < 1 / 2 ? q : t < 2 / 3 ? p + (q - p) * (2 / 3 - t) * 6 : p; };
  return [f(h + 1 / 3), f(h), f(h - 1 / 3)].map(v => Math.round(v * 255));
}
// Flip lightness. Very dark surfaces land near white rather than mid-grey.
function flip(r, g, b) {
  const [h, s, l] = rgbToHsl(r, g, b);
  let nl = 1 - l;
  if (l < 0.2) nl = 0.9 + (0.2 - l) * 0.5;           // dark surfaces -> 0.90-1.00
  return hslToRgb(h, Math.min(s, 0.85), Math.max(0, Math.min(1, nl)));
}
const hex = n => n.toString(16).padStart(2, "0");

function transformColours(value) {
  return value
    .replace(/#([0-9a-fA-F]{3,8})\b/g, (match, h) => {
      if (![3, 4, 6, 8].includes(h.length)) return match;
      const full = h.length <= 4 ? [...h].map(c => c + c).join("") : h;
      const [r, g, b] = [0, 2, 4].map(i => parseInt(full.slice(i, i + 2), 16));
      const alpha = full.length === 8 ? full.slice(6) : "";
      return `#${flip(r, g, b).map(hex).join("")}${alpha}`;
    })
    .replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(,\s*[\d.]+\s*)?\)/g, (_, r, g, b, a) => {
      const [nr, ng, nb] = flip(+r, +g, +b);
      return a ? `rgba(${nr},${ng},${nb}${a})` : `rgb(${nr},${ng},${nb})`;
    })
    .replace(/\b(white|black)\b/g, name => transformColours(NAMED[name]));
}

const COLOUR = /#[0-9a-fA-F]{3,8}\b|rgba?\(|\b(white|black)\b/;
function scopeSelector(selector) {
  return selector.split(",").map(s => s.trim()).filter(Boolean).map(s =>
    s === ":root" || s === "html" ? SCOPE : s.startsWith(":root") ? SCOPE + s.slice(5) : s.startsWith("html") ? SCOPE + s.slice(4) : `${SCOPE} ${s}`,
  ).join(",");
}

// Minimal CSS walker: top-level rules and @media blocks (no nesting deeper than that in globals.css).
function convert(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, "");
  let out = "", i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    if (head.startsWith("@media") || head.startsWith("@supports")) {
      let depth = 1, j = open + 1;
      while (j < css.length && depth) { if (css[j] === "{") depth++; else if (css[j] === "}") depth--; j++; }
      const inner = convert(css.slice(open + 1, j - 1));
      if (inner.trim()) out += `${head}{\n${inner}}\n`;
      i = j; continue;
    }
    const close = css.indexOf("}", open);
    const body = css.slice(open + 1, close);
    if (!head.startsWith("@")) {
      const decls = body.split(";").map(d => d.trim()).filter(d => d && COLOUR.test(d.slice(d.indexOf(":") + 1)));
      if (decls.length) out += `${scopeSelector(head)}{${decls.map(d => { const k = d.indexOf(":"); return `${d.slice(0, k)}:${transformColours(d.slice(k + 1))}`; }).join(";")}}\n`;
    }
    i = close + 1;
  }
  return out;
}

const css = fs.readFileSync(SOURCE, "utf8");
const result = `/* GENERATED by scripts/generate-light-theme.mjs from globals.css. Do not edit by hand. */\n${SCOPE}{color-scheme:light}\n${convert(css)}`;
fs.writeFileSync(TARGET, result);
console.log(`Wrote ${TARGET.pathname} (${result.length} bytes)`);
